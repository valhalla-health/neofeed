// A temp-password account must not be able to touch patient data.
//
// THE GAP (CODE_REVIEW_2026-08-18, unfixed until 2026-08-21):
// `mustChangePassword` was enforced only in the client. `login()` reported it,
// `verifyToken()` even recomputed it fresh from Staff col G on every single
// request — and then **nothing on the server ever acted on it**. The only
// thing standing between an auto-provisioned temp password and the full
// registry was `app.jsx` choosing to render `<ChangePasswordModal forced>`
// instead of the app. Any client that skipped that render — curl, a stale
// bundle, a second tab restored from `sessionStorage` — was fully authorised.
// The comment in `app.jsx` names the danger exactly: *"the token is already
// valid and would otherwise grant full access on the temp password
// indefinitely."* The client author knew. The server never enforced it.
//
// Temp passwords are ~40 bits, generated by `_genTempPassword()`, and written
// in clear text into **Staff col H** for a human to relay. That is a
// deliberately short-lived secret sitting in a spreadsheet, and until this fix
// it was worth exactly as much as a real password.
//
// WHAT THIS PINS: after `verifyToken`, every action except the two that let a
// user escape the state is refused server-side. `changePassword` must keep
// working — a gate with no exit locks the account out permanently — and
// `logout` is handled before `verifyToken` so it is unaffected.
//
// It also pins that the SHEET governs, not the token: `verifyToken` re-reads
// col G, so flipping the sheet closes an already-issued session (Part 4).
//
// Same technique as verify-gas-session-revocation.cjs — every top-level
// statement in gas-backend.gs is a `var` or a function declaration, so the
// file evaluates against stubbed Apps Script globals and `doPost` can be
// driven directly. No dependencies; run with plain
// `node test/verify-must-change-password.cjs`.
const fs = require('fs');
const vm = require('vm');
const path = require('path');

let pass = 0, fail = 0;
function eq(name, got, want) {
  const ok = Object.is(got, want);
  console.log(`  ${ok ? 'PASS' : 'FAIL'}  ${name.padEnd(54)} got ${JSON.stringify(got)}  want ${JSON.stringify(want)}`);
  ok ? pass++ : fail++;
}
function ok(name, cond) { eq(name, !!cond, true); }

// ── Sheet doubles, resolved by tab name ──────────────────────────────────
const STAFF_HEADER = ['email','role','name','active','password_hash','salt','must_change_password','temp_password'];
let staffRows = [];
function makeSheet(getRows) {
  return {
    getDataRange() { return { getValues: () => getRows().map(r => r.slice()) }; },
    getRange() {
      return {
        setValue() {}, setValues() {}, clearContent() {},
        getValue: () => '', getValues: () => [[]],
      };
    },
    appendRow() {},
    deleteRow() {},
    getMaxColumns: () => 8,
    getLastRow() { return getRows().length; },
  };
}
const staffSheet   = makeSheet(() => [STAFF_HEADER, ...staffRows]);
const patientSheet = makeSheet(() => [['sessionId','name','initials','bw','ga','sex','dob','admissionDate','twinSuffix','status','currentBed','diagnosis','weights','lengths','hcs','bedHistory','statusDate','multiplesCount']]);
const logSheet     = makeSheet(() => [['sessionId','date']]);
const auditSheet   = makeSheet(() => [['ts','action','sessionId','actorEmail']]);
function sheetByName(name) {
  if (name === 'Staff') return staffSheet;
  if (name === 'Patient_Registry') return patientSheet;
  if (name === 'Daily_Log') return logSheet;
  if (name === 'Audit_Log') return auditSheet;
  return makeSheet(() => [[]]);
}

let cacheStore = new Map();
let props = new Map([['SPREADSHEET_ID', 'sheet-id'], ['CLIENT_ID', 'client-id.apps.googleusercontent.com']]);

const sandbox = {
  SpreadsheetApp: { openById: () => ({ getSheetByName: sheetByName, insertSheet: sheetByName }) },
  Utilities: {
    getUuid: () => 'tok-' + Math.random().toString(36).slice(2, 10) + '-padding',
    computeHmacSha256Signature: () => [], base64Encode: () => '',
    computeDigest: () => [], DigestAlgorithm: { SHA_256: 'sha256' }, Charset: { UTF_8: 'utf8' },
  },
  PropertiesService: {
    getScriptProperties: () => ({
      getProperty: (k) => (props.has(k) ? props.get(k) : null),
      setProperty: (k, v) => { props.set(k, v); },
      deleteProperty: (k) => { props.delete(k); },
    }),
  },
  CacheService: {
    getScriptCache: () => ({
      get: (k) => (cacheStore.has(k) ? cacheStore.get(k) : null),
      put: (k, v) => { cacheStore.set(k, v); },
      remove: (k) => { cacheStore.delete(k); },
    }),
  },
  LockService: { getScriptLock: () => ({ waitLock() {}, releaseLock() {}, tryLock: () => true }) },
  UrlFetchApp: { fetch: () => ({ getResponseCode: () => 200, getContentText: () => '{}' }) },
  // Unlike the other harnesses' stub, this one KEEPS the serialised text so the
  // response body can actually be read back — jsonOut returns the output
  // object, not the string.
  ContentService: {
    createTextOutput: (t) => ({ _text: t, setMimeType() { return this; } }),
    MimeType: { JSON: 'json' },
  },
  Logger: { log() {} },
  console,
};
sandbox.globalThis = sandbox;
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync(path.join(__dirname, '..', 'gas-backend.gs'), 'utf8'), sandbox);

// email | role | name | active | hash | salt | must_change | temp
const TEMP_DOCTOR = ['doc@hospital.th',  'doctor', 'Doc',  true, 'v2$h', 's', true,  'Tmp-9f3a'];
const TEMP_ADMIN  = ['boss@hospital.th', 'admin',  'Boss', true, 'v2$h', 's', true,  'Tmp-1c7d'];
const OK_DOCTOR   = ['ok@hospital.th',   'doctor', 'Ok',   true, 'v2$h', 's', false, ''];
const OK_ADMIN    = ['sudo@hospital.th', 'admin',  'Sudo', true, 'v2$h', 's', false, ''];
// A Google Workspace account: never password-provisioned, so col G must be
// ignored for it even when something has wrongly set it.
const WORKSPACE   = ['someone@chula.ac.th', 'doctor', 'W', true, '', '', true, ''];

function reset(rows) {
  staffRows = rows;
  cacheStore = new Map();
  props = new Map([['SPREADSHEET_ID', 'sheet-id'], ['CLIENT_ID', 'client-id.apps.googleusercontent.com']]);
}
function post(body) {
  const out = sandbox.doPost({ postData: { contents: JSON.stringify(body) } });
  try { return JSON.parse(out._text); } catch (e) { return { _unparseable: String(out && out._text) }; }
}
function tokenFor(row, mustChangeAtMint) {
  return sandbox.createSession(row[0], row[1], row[2], mustChangeAtMint);
}
// Simulates STAFF_RECHECK_TTL_SECONDS (60s) elapsing — the double has no
// real TTL, so the cached Staff row is evicted by hand.
function expireStaffCache(email) { cacheStore.delete('staffrc_' + String(email).toLowerCase()); }

const BLOCKED_FOR_WRITERS = [
  ['getActivePatients',   {}],
  ['logDailyNutrition',   { sessionId: 'X-1', entry: {} }],
  ['updateDailyNutrition',{ sessionId: 'X-1', entryId: 'e1', entry: {} }],
  ['registerPatient',     { patient: { sessionId: 'X-1' } }],
  ['updatePatient',       { patient: { sessionId: 'X-1' } }],
  ['updateWeights',       { sessionId: 'X-1', weights: [] }],
  ['acquireLogLock',      { sessionId: 'X-1', date: '2026-08-21' }],
  ['releaseLogLock',      { sessionId: 'X-1', date: '2026-08-21' }],
];
const BLOCKED_FOR_ADMINS = [
  ['pseudonymizePatient', { sessionId: 'X-1' }],
  ['deletePatient',       { sessionId: 'X-1' }],
  ['deleteDailyNutrition',{ sessionId: 'X-1', entryId: 'e1' }],
];

console.log('\n1 · 🔴 A temp-password account is refused at the SERVER, not just the client');
{
  reset([TEMP_DOCTOR]);
  const token = tokenFor(TEMP_DOCTOR, true);
  for (const [action, extra] of BLOCKED_FOR_WRITERS) {
    const res = post(Object.assign({ action, token }, extra));
    eq(`${action} is refused`, res.error, 'PasswordChangeRequired');
  }
}

console.log('\n2 · An admin on a temp password is refused too — role does not buy an exemption');
{
  reset([TEMP_ADMIN]);
  const token = tokenFor(TEMP_ADMIN, true);
  for (const [action, extra] of BLOCKED_FOR_ADMINS.concat(BLOCKED_FOR_WRITERS)) {
    const res = post(Object.assign({ action, token }, extra));
    eq(`${action} is refused for an admin`, res.error, 'PasswordChangeRequired');
  }
}

console.log('\n3 · 🚪 The escape hatch stays open — a gate with no exit is a lockout');
{
  reset([TEMP_DOCTOR]);
  const token = tokenFor(TEMP_DOCTOR, true);
  const res = post({ action: 'changePassword', token, oldPassword: 'Tmp-9f3a', newPassword: 'a-real-password' });
  ok('changePassword is NOT blocked by the gate', res.error !== 'PasswordChangeRequired');

  // logout is answered before verifyToken, so it can never be gated — pinned
  // so a future refactor that moves the gate upward cannot strand a session.
  const bye = post({ action: 'logout', token });
  eq('logout still succeeds', bye.ok, true);
}

console.log('\n4 · The SHEET governs, not the token');
{
  // Minted while col G was clear, then the account is flagged in the sheet.
  // verifyToken re-reads col G every request, so the live session must close.
  reset([OK_DOCTOR]);
  const token = tokenFor(OK_DOCTOR, false);
  eq('clean account works to begin with',
     post({ action: 'getActivePatients', token }).error, undefined);

  staffRows = [[...OK_DOCTOR.slice(0, 6), true, 'Tmp-abc']];
  expireStaffCache(OK_DOCTOR[0]);
  eq('flagging col G closes an already-issued session',
     post({ action: 'getActivePatients', token }).error, 'PasswordChangeRequired');

  // And the reverse: clearing col G restores access without a re-login.
  staffRows = [OK_DOCTOR];
  expireStaffCache(OK_DOCTOR[0]);
  eq('clearing col G restores the same session',
     post({ action: 'getActivePatients', token }).error, undefined);
}

console.log('\n5 · A normal account is untouched by any of this');
{
  reset([OK_DOCTOR]);
  const token = tokenFor(OK_DOCTOR, false);
  for (const [action, extra] of BLOCKED_FOR_WRITERS) {
    const res = post(Object.assign({ action, token }, extra));
    ok(`${action} not gated for a clean account`, res.error !== 'PasswordChangeRequired');
  }
  reset([OK_ADMIN]);
  const adminToken = tokenFor(OK_ADMIN, false);
  for (const [action, extra] of BLOCKED_FOR_ADMINS) {
    const res = post(Object.assign({ action, token: adminToken }, extra));
    ok(`${action} not gated for a clean admin`, res.error !== 'PasswordChangeRequired');
  }
}

console.log('\n6 · Google/Workspace accounts are never gated — they have no password to change');
{
  // _usesGoogleSignIn excludes them in verifyToken, so a stray TRUE in col G
  // must not lock out an account that authenticates by Google ID token and has
  // no ChangePasswordModal path to escape through.
  reset([WORKSPACE]);
  const token = tokenFor(WORKSPACE, false);
  const res = post({ action: 'getActivePatients', token });
  ok('a chula.ac.th account with col G TRUE is not gated', res.error !== 'PasswordChangeRequired');
}

console.log('\n7 · The refusal leaks nothing and tells the client what to do');
{
  reset([TEMP_DOCTOR]);
  const token = tokenFor(TEMP_DOCTOR, true);
  const res = post({ action: 'getActivePatients', token });
  const body = JSON.stringify(res);
  eq('says why, in a string a client can branch on', res.error, 'PasswordChangeRequired');
  eq('carries the flag so a client can render the modal', res.mustChangePassword, true);
  ok('no session token echoed back', body.indexOf('tok-') === -1);
  ok('no temp password echoed back', body.indexOf('Tmp-') === -1);
  ok('no patient payload', !('patients' in res) && !('registry' in res));
}

console.log('\n8 · An invalid token is still just Unauthorized, not PasswordChangeRequired');
{
  reset([TEMP_DOCTOR]);
  eq('unknown token', post({ action: 'getActivePatients', token: 'nope-nope-nope' }).error, 'Unauthorized');
  eq('missing token', post({ action: 'getActivePatients' }).error, 'Unauthorized');
}

console.log(`\n${fail === 0 ? '✅' : '❌'}  ${pass} passed, ${fail} failed\n`);
process.exit(fail === 0 ? 0 : 1);
